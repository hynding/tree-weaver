import { createBranch, createKit, createShape, createSvgTree, createTree, DISPLAYS, text, type BranchInit, type DisplayDef } from '@tree-weaver/core';
import { describe, expect, it } from 'vitest';
import { exportComponent, jsxAttrName, tailwindClass, tailwindVariant } from './index';

/** A page tree: a <body> root with these children. */
const pageTree = (name: string, children: BranchInit['children']) =>
  createTree(name, createBranch({ tag: 'body', type: 'root', name: 'Body', children }));

const page = () => {
  const hero = createBranch({
    tag: 'section',
    name: 'Hero',
    styles: { lg: { padding: '4rem 2rem', display: 'grid', 'grid-template-columns': 'repeat(3, minmax(0, 1fr))' }, tablet: { 'grid-template-columns': 'repeat(2, minmax(0, 1fr))' } },
    children: [
      createBranch({ tag: 'h1', children: [text('Grow {fast} & <safe>')] }),
      createBranch({ tag: 'label', attrs: { for: 'email', class: 'btn' }, children: [text('Email')] }),
      createBranch({ tag: 'input', attrs: { id: 'email', readonly: '' } }),
    ],
  });
  const card = () => createBranch({ tag: 'div', name: 'Card', styles: { lg: { color: '#333' } }, children: [text('Hi')] });
  return pageTree('Landing page', [hero, card(), card()]);
};

const file = (out: { files: { path: string; contents: string }[] }, path: string) => {
  const f = out.files.find((x) => x.path === path);
  if (!f) throw new Error(`no ${path} in ${out.files.map((x) => x.path).join(', ')}`);
  return f.contents;
};

describe('exportComponent', () => {
  it('writes a React component with a CSS file and readable class names', () => {
    const kit = createKit('Brand', '.btn { color: red; }');
    const out = exportComponent(page(), { framework: 'react', kits: [kit] });
    expect(out.name).toBe('LandingPage');
    expect(out.entry).toBe('LandingPage.jsx');
    expect(out.files.map((f) => f.path).sort()).toEqual(['LandingPage.css', 'LandingPage.jsx', 'kits.css']);
    const jsx = file(out, 'LandingPage.jsx');
    expect(jsx).toContain(`import './kits.css';`);
    expect(jsx).toContain(`import './LandingPage.css';`);
    expect(jsx).toContain('export default function LandingPage()');
    expect(jsx).toContain('<div className="landing-page">');
    expect(jsx).toContain('className="landing-page__hero"');
    expect(jsx).toContain('className="landing-page__card-2"');
    expect(jsx).toContain('htmlFor="email"');
    expect(jsx).toContain('<input id="email" readOnly />');
    // Braces and angle brackets in text must not become JSX expressions or tags.
    expect(jsx).not.toMatch(/>Grow \{fast\}/);
    expect(jsx).not.toContain('data-tw');
    const css = file(out, 'LandingPage.css');
    expect(css).toContain('.landing-page__hero {');
    expect(css).toMatch(/@media \(max-width: ?1024px\)[^{]*\{\s*\.landing-page__hero \{\s*grid-template-columns: repeat\(2, minmax\(0, 1fr\)\)/);
    expect(file(out, 'kits.css')).toContain('.btn { color: red; }');
  });

  it('writes TypeScript and takes a name', () => {
    const out = exportComponent(page(), { framework: 'react', typescript: true, name: 'marketing hero' });
    expect(out.entry).toBe('MarketingHero.tsx');
  });

  it('writes a Vue single-file component', () => {
    const out = exportComponent(page(), { framework: 'vue' });
    expect(out.files.map((f) => f.path)).toEqual(['LandingPage.vue']);
    const vue = file(out, 'LandingPage.vue');
    expect(vue).toMatch(/^<!-- Generated by Tree Weaver/);
    expect(vue).toContain('<template>');
    expect(vue).toContain('class="landing-page__hero"');
    expect(vue).toContain('<style>');
    expect(vue).not.toContain('{{ fast }}');
  });

  it('writes a Svelte component with global class rules', () => {
    const out = exportComponent(page(), { framework: 'svelte' });
    const svelte = file(out, 'LandingPage.svelte');
    expect(svelte).toContain(':global(.landing-page__hero)');
    expect(svelte).not.toMatch(/>Grow \{fast\}/);
  });

  it('writes an HTML page with its stylesheets', () => {
    const out = exportComponent(page(), { framework: 'html' });
    expect(out.entry).toBe('index.html');
    expect(out.files.map((f) => f.path).sort()).toEqual(['LandingPage.css', 'base.css', 'index.html']);
    const html = file(out, 'index.html');
    expect(html).toMatch(/^<!doctype html>/);
    expect(html).toContain('<link rel="stylesheet" href="LandingPage.css">');
    expect(html).toContain('<body');
  });

  it('writes Tailwind classes with display variants instead of a CSS file', () => {
    const out = exportComponent(page(), { framework: 'react', styling: 'tailwind' });
    expect(out.files.map((f) => f.path)).toEqual(['LandingPage.jsx']);
    const jsx = file(out, 'LandingPage.jsx');
    expect(jsx).toContain('Needs Tailwind CSS');
    expect(jsx).toContain('grid');
    expect(jsx).toContain('[grid-template-columns:repeat(3,minmax(0,1fr))]');
    expect(jsx).toContain('max-[1024px]:[grid-template-columns:repeat(2,minmax(0,1fr))]');
  });

  it('keeps class names valid when the tree name starts with a digit', () => {
    const tree = pageTree('3 columns', [createBranch({ tag: 'div', styles: { lg: { gap: '1rem' } } })]);
    const out = exportComponent(tree, { framework: 'react' });
    expect(out.name).toBe('Layout3Columns');
    expect(file(out, 'Layout3Columns.jsx')).toContain('className="layout-3-columns"');
    expect(file(out, 'Layout3Columns.css')).toContain('.layout-3-columns__div {');
  });

  it('exports an SVG tree with its own root', () => {
    const tree = createSvgTree('Logo', [createShape('circle', { cx: '5', cy: '5', r: '4', 'stroke-width': '2' })], '0 0 10 10');
    const jsx = file(exportComponent(tree, { framework: 'react' }), 'Logo.jsx');
    expect(jsx).toMatch(/<svg [^>]*viewBox="0 0 10 10"/);
    expect(jsx).toContain('strokeWidth="2"');
  });

  it('drops unsafe markup', () => {
    const tree = pageTree('X', [createBranch({ tag: 'div', attrs: { onclick: 'alert(1)', href: 'javascript:alert(1)' }, children: [text('ok')] })]);
    for (const framework of ['react', 'vue', 'svelte', 'html'] as const) {
      const all = exportComponent(tree, { framework }).files.map((f) => f.contents).join('\n');
      expect(all).not.toMatch(/onclick|javascript:/i);
    }
  });

  it('links kits with an href by @import', () => {
    const kit = { ...createKit('Remote', ''), href: 'https://cdn.example.com/a.css' };
    const out = exportComponent(page(), { framework: 'react', kits: [kit] });
    expect(file(out, 'kits.css')).toContain('@import url("https://cdn.example.com/a.css")');
  });
});

describe('Tailwind helpers', () => {
  it('maps displays to variants', () => {
    const byId = (id: string) => DISPLAYS.find((d) => d.id === id) as DisplayDef;
    expect(tailwindVariant(byId('lg'))).toBe('');
    expect(tailwindVariant(byId('tablet'))).toBe('max-[1024px]:');
    expect(tailwindVariant(byId('mobile-portrait'))).toMatch(/^max-\[\d+px\]:portrait:$/);
    expect(tailwindVariant(byId('xl'))).toBe('min-[1440px]:');
  });

  it('uses named utilities where they exist and arbitrary properties otherwise', () => {
    expect(tailwindClass('display', 'flex')).toBe('flex');
    expect(tailwindClass('text-align', 'center')).toBe('text-center');
    expect(tailwindClass('padding', '1rem')).toBe('p-[1rem]');
    expect(tailwindClass('padding', '1rem 2rem')).toBe('[padding:1rem_2rem]');
    expect(tailwindClass('font-family', '"Open Sans", serif')).toBe('[font-family:"Open_Sans",serif]');
  });

  it('renames attributes for JSX', () => {
    expect(jsxAttrName('class')).toBe('className');
    expect(jsxAttrName('for')).toBe('htmlFor');
    expect(jsxAttrName('stroke-width')).toBe('strokeWidth');
    expect(jsxAttrName('viewBox')).toBe('viewBox');
    expect(jsxAttrName('aria-label')).toBe('aria-label');
    expect(jsxAttrName('data-x')).toBe('data-x');
  });
});
